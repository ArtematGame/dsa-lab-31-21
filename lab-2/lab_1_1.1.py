# Пункт 1 - Поиск минимального числа
print("Пункт 1\n")

try:
    # Запрос трех чисел у пользователя и преобразование в вещественный тип
    a = float(input("Введите первое число: "))
    b = float(input("Введите второе число: "))
    c = float(input("Введите третье число: "))
    
    # Нахождение минимального числа через функцию min()
    min_num = (min(a, b, c))
    
    # Вывод результата
    print(f"Минимальное число: {min_num}\n")
    
# Обработка исключения при вводе некорректных данных
except ValueError:
    print("Ошибка! Введите число.\n")

# Пункт 2 - Поиск чисел в диапазоне от 1 до 50
print("Пункт 2\n")

try:
    # Запрос трех целых чисел
    a2 = int(input("Введите первое число: "))
    b2 = int(input("Введите второе число: "))
    c2 = int(input("Введите третье число: "))
    
    print("Числа в промежутке от 1 до 50: ")
    
    # Проверка каждого числа на принадлежность диапазону [1, 50]
    # Вывод числа при попадании в диапазон
    if 1 <= a2 <= 50:
        print(a2)
    if 1 <= b2 <= 50:
        print(b2)
    if 1 <= c2 <= 50:
        print(c2)
    print()
    
except ValueError:
    print("Ошибка! Введите число.\n")

# Пункт 3 - Таблица умножения для введенного числа
print("Пункт 3\n")

try:
    # Запрос вещественного числа m
    m = float(input("Введите вещественное число m: "))
    
    # Проверка на положительное значение
    if m <= 0:
        print("Ошибка! Введите положительное число.\n")
    else:
        print("Результат: ")
        
        # Цикл для умножения числа m на числа от 1 до 10
        for i in range(1, 11):
            result = i * m
            # Вывод результата с двумя знаками после запятой
            print(f"{i} * {m} = {result:.2f}")
        print()
        
except ValueError:
    print("Ошибка! Введите число.\n")

# Пункт 4 - Сумма и количество чисел из введенной строки
print("Пункт 4\n")

try:
    # Ввод строки с числами через пробел и преобразование в список целых чисел
    numbers = list(map(int, input().split()))
    
    i = 0
    summa = 0
    count = 0
    
    # Цикл для обхода всех элементов списка
    while i < len(numbers):
        summa += numbers[i]  # Добавление текущего числа к сумме
        count += 1            # Увеличение счетчика
        i += 1                # Переход к следующему элементу
    
    # Вывод результатов
    print(f"Сумма: {summa}")
    print(f"Количество: {count}")
    
except ValueError:
    print("Ошибка! Введите только целые числа через пробел")